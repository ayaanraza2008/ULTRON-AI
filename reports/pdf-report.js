import { PDFDocument } from "pdfkit";

const CP1252 = new Set([
  0x20ac,0x201a,0x0192,0x201e,0x2026,0x2020,0x2021,0x02c6,0x2030,0x0160,
  0x2039,0x0152,0x017d,0x2018,0x2019,0x201c,0x201d,0x2022,0x2013,0x2014,
  0x02dc,0x2122,0x0161,0x203a,0x0153,0x017e,0x0178
]);
const MAX_CHARS = 40000;
const MAX_SECTIONS = 40;

function cleanText(value, max) {
  return typeof value === "string"
    ? value.replace(/\r\n?/g, "\n").replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, " ").slice(0, max)
    : "";
}

function toWinAnsiText(value) {
  let text = "";
  let replacements = 0;
  for (const char of value) {
    const cp = char.codePointAt(0);
    if (cp <= 0x7e || (cp >= 0xa0 && cp <= 0xff) || CP1252.has(cp)) {
      text += char;
    } else {
      text += "?";
      replacements++;
    }
  }
  return { text, replacements };
}

function collectPdf(doc) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    doc.on("data", chunk => chunks.push(chunk));
    doc.once("end", () => resolve(Buffer.concat(chunks)));
    doc.once("error", reject);
  });
}

/**
 * Generate a transient PDF using PDFKit rather than hand-assembling PDF
 * objects and cross-reference offsets. PDFKit owns serialization/xref details;
 * source content remains bounded and is never written to disk.
 */
export async function generateReportPdf(input = {}) {
  const title = cleanText(input.title || "ULTRON Report", 120).trim() || "ULTRON Report";
  const content = cleanText(input.content || "", MAX_CHARS + 1);
  const inputSections = Array.isArray(input.sections) ? input.sections : [];
  if (inputSections.length > MAX_SECTIONS) {
    return { ok: false, code: "REPORT_TOO_MANY_SECTIONS", message: "A report can contain at most " + MAX_SECTIONS + " sections." };
  }

  const sections = inputSections.map((item, i) => ({
    heading: cleanText(item?.heading || "Section " + (i + 1), 160).trim(),
    content: cleanText(item?.content || "", 10000)
  }));
  if (!content.trim() && !sections.some(section => section.content.trim())) {
    return { ok: false, code: "REPORT_CONTENT_REQUIRED", message: "Provide report content or at least one non-empty section." };
  }

  const total = title.length + content.length + sections.reduce((sum, section) => sum + section.heading.length + section.content.length, 0);
  if (total > MAX_CHARS) {
    return { ok: false, code: "REPORT_TOO_LARGE", message: "Report text must be " + MAX_CHARS + " characters or fewer." };
  }

  const titleText = toWinAnsiText(title);
  const bodyText = toWinAnsiText(content);
  const normalizedSections = sections.map(section => ({
    heading: toWinAnsiText(section.heading),
    content: toWinAnsiText(section.content)
  }));
  const unsupportedCharacterCount = titleText.replacements + bodyText.replacements
    + normalizedSections.reduce((sum, section) => sum + section.heading.replacements + section.content.replacements, 0);

  try {
    const doc = new PDFDocument({
      size: "LETTER",
      margins: { top: 54, bottom: 54, left: 54, right: 54 },
      info: { Title: titleText.text, Author: "ULTRON AI", Producer: "ULTRON AI" },
      compress: true
    });
    const pdfPromise = collectPdf(doc);
    let pages = 1;
    doc.on("pageAdded", () => { pages++; });

    doc.font("Helvetica-Bold").fontSize(18).fillColor("#111111").text(titleText.text, { paragraphGap: 4 });
    doc.moveDown(0.35);
    doc.font("Helvetica").fontSize(8).fillColor("#666666").text("Generated by ULTRON AI - " + new Date().toISOString());
    if (unsupportedCharacterCount > 0) {
      doc.moveDown(0.4);
      doc.font("Helvetica").fontSize(8).fillColor("#555555")
        .text("Note: Some unsupported script characters are displayed as \"?\" by the built-in PDF font.");
    }

    if (bodyText.text.trim()) {
      doc.moveDown(0.6);
      doc.font("Helvetica").fontSize(10).fillColor("#222222").text(bodyText.text, { paragraphGap: 2, lineGap: 2 });
    }

    for (const section of normalizedSections) {
      doc.moveDown(0.55);
      doc.font("Helvetica-Bold").fontSize(13).fillColor("#111111")
        .text(section.heading.text || "Section", { paragraphGap: 4 });
      if (section.content.text.trim()) {
        doc.moveDown(0.1);
        doc.font("Helvetica").fontSize(10).fillColor("#222222")
          .text(section.content.text, { paragraphGap: 2, lineGap: 2 });
      }
    }

    doc.end();
    const pdf = await pdfPromise;
    return {
      ok: true,
      pdf,
      filename: "ultron-report.pdf",
      pages,
      characters: total,
      unsupportedCharacterCount,
      unicodeSupport: "WinAnsi characters are supported; unsupported scripts are replaced with '?'. Report content is not stored."
    };
  } catch {
    return {
      ok: false,
      code: "REPORT_GENERATION_FAILED",
      message: "The PDF report could not be generated."
    };
  }
}
