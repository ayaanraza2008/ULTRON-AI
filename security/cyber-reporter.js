/**
 * ULTRON AI — Advanced Ethical Hacking & Cybersecurity System
 * Module: CYBERSECURITY REPORT GENERATOR (security/cyber-reporter.js)
 *
 * Generates professional executive and technical security reports in
 * Markdown, HTML, and structured JSON formats.
 */

export class CyberReporter {
  /**
   * Format a full cybersecurity assessment report in Markdown
   */
  generateMarkdownReport(assessmentData = {}) {
    const {
      title = "ULTRON AI — CYBERSECURITY ASSESSMENT REPORT",
      target = "localhost",
      organization = "Authorized Client Organization",
      scopeId = "scope-default",
      assessor = "ULTRON CYBER CORE v2.0",
      findings = [],
      overallRisk = "NOT_ASSESSED",
      maxCvss = 0,
      methodology = "Module-specific passive checks and caller-supplied evidence analysis",
      evidenceMode = "NOT_SPECIFIED",
      verificationStatus = "NOT_INDEPENDENTLY_VERIFIED",
      evidenceSummary = {}
    } = assessmentData;

    const criticalCount = findings.filter(f => f.severity === "CRITICAL").length;
    const highCount = findings.filter(f => f.severity === "HIGH").length;
    const mediumCount = findings.filter(f => f.severity === "MEDIUM").length;
    const lowCount = findings.filter(f => f.severity === "LOW").length;

    let md = `# ${title}\n\n`;
    md += `> **Target:** \`${target}\`  \n`;
    md += `> **Organization:** ${organization}  \n`;
    md += `> **Authorization Scope ID:** \`${scopeId}\`  \n`;
    md += `> **Assessment Engine:** ${assessor}  \n`;
    md += `> **Date:** ${new Date().toISOString()}  \n`;
    md += `> **Testing Methodology:** ${methodology}\n\n`;
    md += `---\n\n`;

    md += `## 1. EXECUTIVE SUMMARY\n\n`;
    md += `ULTRON Cyber Core conducted an authorized security assessment against \`${target}\`.  \n`;
    md += `- **Overall Risk Posture:** **${overallRisk}** (Max CVSS: **${maxCvss.toFixed(1)}/10.0**)\n`;
    md += `- **Total Identified Findings:** **${findings.length}**\n`;
    md += `  - 🔴 **Critical:** ${criticalCount}\n`;
    md += `  - 🟠 **High:** ${highCount}\n`;
    md += `  - 🟡 **Medium:** ${mediumCount}\n`;
    md += `  - 🔵 **Low:** ${lowCount}\n\n`;

    md += `## 2. FINDINGS & TECHNICAL EVIDENCE\n\n`;
    if (findings.length === 0) {
      md += `*No security vulnerabilities identified in the authorized testing scope. System demonstrates strong defensive hardening.*\n\n`;
    } else {
      findings.forEach((f, idx) => {
        md += `### ${idx + 1}. [${f.severity}] ${f.title || f.name} (${f.cwe || f.cve || "VULN"})\n\n`;
        md += `- **Affected Asset:** \`${f.affectedAsset || target}\`\n`;
        md += `- **CVSS v3.1 Base Score:** \`${f.cvss || f.cvssScore || "N/A"}\`\n`;
        md += `- **Confidence:** \`${((f.confidence || 0.95) * 100).toFixed(0)}%\`\n`;
        md += `- **Technical Evidence:** \`${f.evidence || f.snippet || "Observed during scan"}\`\n`;
        md += `- **Potential Impact:** ${f.impact || f.businessImpact || f.description || "Security risk"}\n`;
        md += `- **Remediation Advice:** ${f.remediation || "Follow security patching guidelines."}\n\n`;
      });
    }

    md += `## 3. REMEDIATION ROADMAP\n\n`;
    md += `1. Immediately remediate all **CRITICAL** and **HIGH** severity findings within 24–48 hours.\n`;
    md += `2. Re-run \`ULTRON Cyber Core\` automated verification tests after applying recommended patches.\n`;
    md += `3. Verify that all secret credentials have been rotated and purged from source history.\n\n`;

    md += `---\n*Report generated by ULTRON CYBER CORE. Strictly for authorized operator review.*`;
    return md;
  }

  /**
   * Format HTML report for Cyber-HUD export
   */
  generateHtmlReport(assessmentData = {}) {
    const md = this.generateMarkdownReport(assessmentData);
    return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>ULTRON Cyber Core Security Assessment Report</title>
  <style>
    body { font-family: monospace, sans-serif; background: #0a0d14; color: #f1f5f9; padding: 24px; line-height: 1.6; }
    h1, h2, h3 { color: #00f0ff; }
    code { background: #1e293b; padding: 2px 6px; border-radius: 4px; color: #38bdf8; }
    hr { border: 1px solid #1e293b; margin: 20px 0; }
  </style>
</head>
<body>
  <pre style="white-space: pre-wrap;">${md.replace(/</g, "&lt;").replace(/>/g, "&gt;")}</pre>
</body>
</html>`;
  }
}

export const cyberReporter = new CyberReporter();
